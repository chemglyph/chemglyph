# Structures PubChem resolves wrongly by name, written by hand and checked by
# formula. "triphenylmethyl radical" resolves to triphenylmethane (C19H16), and
# "cis-decalin" and "trans-decalin" both resolve to decalin without stereo.
MANUAL: list[tuple[str, str, str, str]] = [
    ("triphenylmethyl radical", "radicals", "[C](c1ccccc1)(c1ccccc1)c1ccccc1", "C19H15"),
    ("cis-decalin", "stereochemistry", "C1CC[C@H]2CCCC[C@H]2C1", "C10H18"),
    ("trans-decalin", "stereochemistry", "C1CC[C@@H]2CCCC[C@H]2C1", "C10H18"),
]

_URL = (
    "https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{}/property/"
    "SMILES,MolecularFormula/JSON"
)


def _lookup(name: str) -> dict | None:
    url = _URL.format(urllib.parse.quote(name, safe=""))
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            properties = json.load(response)["PropertyTable"]["Properties"][0]
    except Exception:
        return None
    smiles = properties.get("SMILES") or properties.get("IsomericSMILES")
    if not smiles:
        return None
    return {"cid": properties["CID"], "smiles": smiles, "formula": properties["MolecularFormula"]}


def main() -> None:
    from rdkit import Chem
    from rdkit.Chem import rdMolDescriptors

    out = Path(__file__).resolve().parent / "corpus.csv"
    manual_names = {name for name, *_ in MANUAL}
    rows, missing, seen, cids = [], [], set(), set()
    for category, names in CATEGORIES.items():
        for name in names:
            if name in seen or name in manual_names:
                continue
            seen.add(name)
            record = _lookup(name)
            time.sleep(0.25)  # PubChem asks for at most five requests per second
            if record is None:
                missing.append(name)
                continue
            if record["cid"] in cids:
                continue  # another name already brought this compound
            cids.add(record["cid"])
            rows.append({"name": name, "category": category, "source": "pubchem", **record})
    for name, category, smiles, formula in MANUAL:
        computed = rdMolDescriptors.CalcMolFormula(Chem.MolFromSmiles(smiles))
        assert computed == formula, (name, computed, formula)
        rows.append(
            {
                "name": name,
                "category": category,
                "source": "manual",
                "cid": "",
                "formula": formula,
                "smiles": smiles,
            }
        )
    with out.open("w", newline="", encoding="utf-8") as handle:
        fields = ["name", "category", "source", "cid", "formula", "smiles"]
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} structures to {out}")
    if missing:
        print(f"not found on PubChem ({len(missing)}): {', '.join(missing)}")


if __name__ == "__main__":
    main()
